import { useEffect, useState } from 'react';
import {
  nodeOwnKpis, performanceRollup, varianceRollup, ownerName, ownerKindLabel,
  subsOfProgramme, unitsOfSub, employeesOfUnit,
  reachableOrgSlice, availableReportKinds, GLOBAL_REPORT_ROLES, defaultNodeForRole,
} from '../lib/scope.js';

const KIND_LABEL = { overall: 'Overall', programme: 'Programme', sub: 'Sub-programme', unit: 'Unit', employee: 'Staff member' };

function optionsFor(kind, slice) {
  if (kind === 'programme') return slice.programmes;
  if (kind === 'sub') return slice.subs;
  if (kind === 'unit') return slice.units;
  if (kind === 'employee') return slice.employees;
  return [];
}
// Units carry a "kind" label (Unit/Department/Faculty/Region/Regional
// Campus — see OrganisationBuilder.jsx's CREATE_UNIT_TYPES) that's often
// the more meaningful word for what the entity actually is, so the picker
// shows it rather than a bare name — "Department: Finance", not "Finance".
function optionLabel(kind, entity) {
  if (kind === 'unit') return `${entity.kind || 'Unit'}: ${entity.name}`;
  return entity.name;
}

// A single, focused, downloadable report for exactly one entity — a
// specific staff member, Unit, Sub-programme, Programme, or (for a global
// role) the whole institution — at whatever cadence the page's own
// PeriodTypePicker has selected (see Reports.jsx, which passes periodLabel
// straight through so this section is never on a period of its own that
// could drift from the rest of the page). This is the per-entity companion
// to the always-on Programme/Sub-programme/Unit rollup table above it:
// that table answers "how is everything doing", this answers "give me one
// real, citable document about just this one person or unit".
export default function FocusedReportSection({ org, kpis, perfValues, settings, user, periodLabel }) {
  const kinds = availableReportKinds(user);
  const isGlobal = GLOBAL_REPORT_ROLES.includes(user.role);
  const root = isGlobal ? null : defaultNodeForRole(user);
  const slice = reachableOrgSlice(org, root);
  const [kind, setKind] = useState(kinds[0] || 'overall');
  const options = kind === 'overall' ? [] : optionsFor(kind, slice);
  const [entityId, setEntityId] = useState(options[0]?.id ?? null);
  const [pdfBusy, setPdfBusy] = useState(false);

  // Re-pick a default entity every time the level changes — the previous
  // id almost never exists in the new level's option list.
  useEffect(() => {
    const opts = kind === 'overall' ? [] : optionsFor(kind, slice);
    setEntityId(opts[0]?.id ?? null);
    // eslint-disable-next-line react-hooks/exhaustive-deps
  }, [kind]);

  if (kinds.length === 0) {
    return (
      <div className="card mb-5">
        <h2 className="font-display font-bold text-[14.5px] mb-2">Generate a focused report</h2>
        <p className="text-[12.5px] text-ink-muted">
          Individual performance reports are generated by whoever reviews your work, not self-served — there's
          nothing to generate here for your own account.
        </p>
      </div>
    );
  }

  const entity = kind === 'overall' ? null : options.find((o) => o.id === entityId) || null;
  const entityName = kind === 'overall'
    ? (isGlobal ? 'Overall — university-wide' : 'Overall — my jurisdiction')
    : (entity ? optionLabel(kind, entity) : null);
  const ready = kind === 'overall' || !!entity;

  const kpiList = kind === 'overall' ? kpis : (entity ? nodeOwnKpis(org, kpis, kind, entity.id) : []);
  const rollup = performanceRollup(kpiList, perfValues, settings);
  const variance = varianceRollup(kpiList, perfValues, settings);

  // The next tier down — so a focused report also shows how its own
  // averaged number is actually made up, not just a single figure.
  let children = [];
  let childKind = null;
  if (kind === 'overall') {
    childKind = 'programme';
    children = slice.programmes.map((p) => ({ id: p.id, name: p.name, ...performanceRollup(nodeOwnKpis(org, kpis, 'programme', p.id), perfValues, settings) }));
  } else if (kind === 'programme' && entity) {
    childKind = 'sub';
    children = subsOfProgramme(org, entity.id).map((s) => ({ id: s.id, name: s.name, ...performanceRollup(nodeOwnKpis(org, kpis, 'sub', s.id), perfValues, settings) }));
  } else if (kind === 'sub' && entity) {
    childKind = 'unit';
    children = unitsOfSub(org, entity.id).map((u) => ({ id: u.id, name: `${u.kind || 'Unit'}: ${u.name}`, ...performanceRollup(nodeOwnKpis(org, kpis, 'unit', u.id), perfValues, settings) }));
  } else if (kind === 'unit' && entity && user.role !== 'employee') {
    childKind = 'employee';
    children = employeesOfUnit(org, entity.id).map((e) => ({ id: e.id, name: e.name, ...performanceRollup(nodeOwnKpis(org, kpis, 'employee', e.id), perfValues, settings) }));
  }

  function ragCls(pct) {
    if (pct == null) return 'chip-rag-none';
    const green = Number(settings.ragGreen ?? 80), amber = Number(settings.ragAmber ?? 50);
    return pct >= green ? 'chip-rag-green' : pct >= amber ? 'chip-rag-amber' : 'chip-rag-red';
  }
  function fileStem() {
    return `zou-report-${(entityName || 'overall').replace(/[^a-z0-9]+/gi, '-')}-${periodLabel.replace(/\s+/g, '-')}`;
  }

  function downloadCsv() {
    const rows = [['KPI', 'Owner', 'Owner tier', 'Baseline', 'Target', 'Progress %', 'Pace flag']];
    variance.items.forEach(({ kpi, actualPct, flag }) => {
      rows.push([kpi.name, ownerName(org, kpi), ownerKindLabel(kpi), kpi.baseline, kpi.target, actualPct ?? '', flag]);
    });
    const csv = rows.map((r) => r.map((c) => `"${String(c ?? '').replace(/"/g, '""')}"`).join(',')).join('\n');
    const blob = new Blob([csv], { type: 'text/csv' });
    const url = URL.createObjectURL(blob);
    const a = document.createElement('a');
    a.href = url;
    a.download = `${fileStem()}.csv`;
    a.click();
    URL.revokeObjectURL(url);
  }

  async function downloadPdf() {
    setPdfBusy(true);
    let jsPDF, autoTable;
    try {
      [{ jsPDF }, { default: autoTable }] = await Promise.all([import('jspdf'), import('jspdf-autotable')]);
    } catch {
      setPdfBusy(false);
      window.alert('Could not load the PDF generator. Check your connection and try again.');
      return;
    }
    const doc = new jsPDF({ unit: 'pt', format: 'a4' });
    const marginX = 40;
    let y = 46;
    doc.setFont('helvetica', 'bold'); doc.setFontSize(15);
    doc.text('ZOU Strategic Plan Monitor — Performance Report', marginX, y); y += 18;
    doc.setFont('helvetica', 'normal'); doc.setFontSize(10.5);
    doc.text(`${KIND_LABEL[kind]} · ${entityName} · ${periodLabel} · Generated ${new Date().toLocaleString()}`, marginX, y);
    y += 22;

    doc.setFont('helvetica', 'bold'); doc.setFontSize(12);
    doc.text('Summary', marginX, y); y += 8;
    autoTable(doc, {
      startY: y + 6,
      margin: { left: marginX, right: marginX },
      head: [['KPIs', 'Avg. progress', 'On track', 'At risk', 'Off track', 'No data']],
      body: [[String(rollup.count), rollup.avgPct != null ? `${rollup.avgPct}%` : '—', rollup.counts.green, rollup.counts.amber, rollup.counts.red, rollup.counts.none]],
      styles: { fontSize: 9, cellPadding: 4 },
      headStyles: { fillColor: [21, 20, 15], textColor: 255 },
    });
    y = doc.lastAutoTable.finalY + 22;

    if (children.length > 0) {
      if (y > 700) { doc.addPage(); y = 46; }
      doc.setFont('helvetica', 'bold'); doc.setFontSize(12);
      doc.text(`By ${KIND_LABEL[childKind]}`, marginX, y); y += 8;
      autoTable(doc, {
        startY: y + 6,
        margin: { left: marginX, right: marginX },
        head: [[KIND_LABEL[childKind], 'KPIs', 'Avg. progress', 'On track', 'At risk', 'Off track', 'No data']],
        body: children.map((c) => [c.name, c.count, c.avgPct != null ? `${c.avgPct}%` : '—', c.counts.green, c.counts.amber, c.counts.red, c.counts.none]),
        styles: { fontSize: 8.5, cellPadding: 4 },
        headStyles: { fillColor: [21, 20, 15], textColor: 255 },
      });
      y = doc.lastAutoTable.finalY + 22;
    }

    if (y > 700) { doc.addPage(); y = 46; }
    doc.setFont('helvetica', 'bold'); doc.setFontSize(12);
    doc.text('Own KPIs', marginX, y); y += 8;
    if (variance.items.length > 0) {
      autoTable(doc, {
        startY: y + 6,
        margin: { left: marginX, right: marginX },
        head: [['KPI', 'Owner', 'Baseline', 'Target', 'Progress %', 'Pace']],
        body: variance.items.map(({ kpi, actualPct, flag }) => [
          kpi.name, `${ownerName(org, kpi)} (${ownerKindLabel(kpi)})`, kpi.baseline, kpi.target,
          actualPct != null ? `${actualPct}%` : '—',
          flag === 'attention' ? 'Behind pace' : flag === 'ahead' ? 'Ahead of pace' : flag === 'on-pace' ? 'On pace' : '—',
        ]),
        styles: { fontSize: 8.5, cellPadding: 4 },
        headStyles: { fillColor: [21, 20, 15], textColor: 255 },
      });
    } else {
      doc.setFont('helvetica', 'normal'); doc.setFontSize(9.5);
      doc.text('No KPIs at this level.', marginX, y + 8);
    }

    const pageCount = doc.internal.getNumberOfPages();
    for (let i = 1; i <= pageCount; i++) {
      doc.setPage(i); doc.setFontSize(8); doc.setTextColor(140);
      doc.text(`ZOU IRBM Strategic Plan Monitor · Page ${i} of ${pageCount}`, marginX, 815);
      doc.setTextColor(0);
    }
    doc.save(`${fileStem()}.pdf`);
    setPdfBusy(false);
  }

  return (
    <div className="card mb-5">
      <div className="flex justify-between gap-4 flex-wrap items-start mb-3">
        <div>
          <h2 className="font-display font-bold text-[14.5px] mb-0.5">Generate a focused report</h2>
          <p className="text-[12px] text-ink-muted max-w-[62ch]">
            One entity at a time — a single staff member, Unit/Department/Faculty/Region, Sub-programme, Programme,
            or your whole jurisdiction — at the period already selected above ({periodLabel}).
          </p>
        </div>
        <div className="no-print flex gap-2 flex-wrap items-center">
          <button className="btn btn-sm" onClick={downloadCsv} disabled={!ready}>Download CSV</button>
          <button className="btn btn-sm btn-primary" disabled={pdfBusy || !ready} onClick={downloadPdf}>{pdfBusy ? 'Preparing…' : 'Download PDF'}</button>
        </div>
      </div>

      <div className="no-print flex gap-2 flex-wrap items-center mb-3">
        <select className="field-input py-1.5 w-auto" aria-label="Report level" value={kind} onChange={(e) => setKind(e.target.value)}>
          {kinds.map((k) => <option key={k} value={k}>{KIND_LABEL[k]}</option>)}
        </select>
        {kind !== 'overall' && (
          <select className="field-input py-1.5 w-auto max-w-[280px]" aria-label={KIND_LABEL[kind]} value={entityId ?? ''} onChange={(e) => setEntityId(Number(e.target.value))}>
            {options.length === 0 && <option value="">None available</option>}
            {options.map((o) => <option key={o.id} value={o.id}>{optionLabel(kind, o)}</option>)}
          </select>
        )}
      </div>
      {ready && (
        <p className="hidden print:block text-[12px] font-semibold mb-2">{KIND_LABEL[kind]} — {entityName}</p>
      )}

      {ready ? (
        <>
          <div className="flex flex-wrap gap-2 mb-3">
            <SummaryStat label="KPIs" value={rollup.count} />
            <SummaryStat label="Avg. progress" value={rollup.avgPct != null ? `${rollup.avgPct}%` : '—'} cls={ragCls(rollup.avgPct)} />
            <SummaryStat label="On track" value={rollup.counts.green} cls="chip-rag-green" />
            <SummaryStat label="At risk" value={rollup.counts.amber} cls="chip-rag-amber" />
            <SummaryStat label="Off track" value={rollup.counts.red} cls="chip-rag-red" />
            <SummaryStat label="No data" value={rollup.counts.none} cls="chip-rag-none" />
          </div>

          {children.length > 0 && (
            <div className="rounded-lg border border-line overflow-x-auto mb-3">
              <table className="w-full text-[12px]">
                <thead>
                  <tr className="bg-sunken text-[10.5px] uppercase tracking-wide text-ink-muted font-bold">
                    <th className="px-3 py-2 text-left">{KIND_LABEL[childKind]}</th>
                    <th className="px-3 py-2 text-left">KPIs</th>
                    <th className="px-3 py-2 text-left">Avg. progress</th>
                  </tr>
                </thead>
                <tbody>
                  {children.map((c) => (
                    <tr key={c.id} className="border-t border-line">
                      <td className="px-3 py-2">{c.name}</td>
                      <td className="px-3 py-2 tabular-nums">{c.count}</td>
                      <td className="px-3 py-2 tabular-nums">{c.avgPct != null ? `${c.avgPct}%` : '—'}</td>
                    </tr>
                  ))}
                </tbody>
              </table>
            </div>
          )}

          <div className="rounded-lg border border-line overflow-x-auto max-h-[40vh] overflow-y-auto">
            <table className="w-full text-[12px]">
              <thead className="sticky top-0">
                <tr className="bg-sunken text-[10.5px] uppercase tracking-wide text-ink-muted font-bold">
                  <th className="px-3 py-2 text-left">KPI</th>
                  <th className="px-3 py-2 text-left">Owner</th>
                  <th className="px-3 py-2 text-left">Progress</th>
                  <th className="px-3 py-2 text-left">Pace</th>
                </tr>
              </thead>
              <tbody>
                {variance.items.length === 0 && (
                  <tr><td className="px-3 py-3 text-ink-muted" colSpan={4}>No KPIs at this level.</td></tr>
                )}
                {variance.items.map(({ kpi, actualPct, flag }) => (
                  <tr key={kpi.id} className="border-t border-line">
                    <td className="px-3 py-2">{kpi.name}</td>
                    <td className="px-3 py-2 text-ink-secondary">{ownerName(org, kpi)} <span className="text-ink-muted">({ownerKindLabel(kpi)})</span></td>
                    <td className="px-3 py-2"><span className={`chip ${ragCls(actualPct)}`}>{actualPct != null ? `${actualPct}%` : 'No data'}</span></td>
                    <td className="px-3 py-2">
                      {flag === 'attention' && <span className="chip chip-rag-red">Behind pace</span>}
                      {flag === 'ahead' && <span className="chip chip-rag-green">Ahead of pace</span>}
                      {flag === 'on-pace' && <span className="chip chip-rag-amber">On pace</span>}
                      {flag === 'none' && <span className="chip chip-rag-none">—</span>}
                    </td>
                  </tr>
                ))}
              </tbody>
            </table>
          </div>
        </>
      ) : (
        <p className="text-[12.5px] text-ink-muted">Nothing to show yet — no {KIND_LABEL[kind].toLowerCase()} is in your reporting jurisdiction.</p>
      )}
    </div>
  );
}

function SummaryStat({ label, value, cls }) {
  return (
    <div className={`rounded-lg px-3 py-2 min-w-[100px] ${cls || 'bg-sunken text-ink-secondary'}`}>
      <div className="text-[10px] uppercase tracking-wide font-bold opacity-80">{label}</div>
      <div className="font-display font-extrabold text-[18px] tabular-nums">{value}</div>
    </div>
  );
}
